/// One row of the vanilla `mobjinfo` table (`mobjinfo_t`).
///
/// `mass` and `damage` are plain ints in vanilla and stay so. `speed` keeps
/// its vanilla dual meaning: plain ints (used per-tic by monster movement)
/// for monsters, fixed-point values (`N*FRACUNIT`, used by `FixedMul` on
/// projectiles) for missiles. Stored as the raw vanilla int - use it exactly
/// the way vanilla does. `radius` and `height` were `N*FRACUNIT` in the
/// table and are [`Fixed`] here (raw vanilla values preserved).
/// `doomednum` is `-1` for things that never spawn from maps (player,
/// missiles, effects).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct MobjInfo {
    /// DoomEd map number; `-1` = not spawned from maps.
    pub doomednum: i32,
    pub spawnstate: StateId,
    pub spawnhealth: i32,
    pub seestate: StateId,
    pub seesound: SfxId,
    pub reactiontime: i32,
    pub attacksound: SfxId,
    pub painstate: StateId,
    pub painchance: i32,
    pub painsound: SfxId,
    pub meleestate: StateId,
    pub missilestate: StateId,
    pub deathstate: StateId,
    pub xdeathstate: StateId,
    pub deathsound: SfxId,
    /// See the type docs: raw vanilla `speed`, plain or fixed-point.
    pub speed: i32,
    pub radius: Fixed,
    pub height: Fixed,
    pub mass: i32,
    pub damage: i32,
    pub activesound: SfxId,
    /// Bitmask of the `MF_*` flags.
    pub flags: u32,
    pub raisestate: StateId,
}

impl MobjInfo {
    /// True if the `flag` bit (or bits) are set. Matches vanilla
    /// `flags & MF_X` truthiness (any bit counts).
    pub const fn has_flag(&self, flag: u32) -> bool {
        self.flags & flag != 0
    }
}

