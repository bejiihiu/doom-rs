// `MF_*` flags (vanilla `p_mobj.h`). Plain bit values, kept as `u32`
// constants like vanilla; `MF_TRANSSHIFT`/`MF_TRANSLATION` are a shift/a mask,
// not standalone flags.
/// `MF_SPECIAL` - call `P_SpecialThing` when touched (vanilla `p_mobj.h`).
pub const MF_SPECIAL: u32 = 0x0000_0001;
/// `MF_SOLID` - blocks.
pub const MF_SOLID: u32 = 0x0000_0002;
/// `MF_SHOOTABLE` - can be hit.
pub const MF_SHOOTABLE: u32 = 0x0000_0004;
/// `MF_NOSECTOR` - don't use the sector links (invisible but touchable).
pub const MF_NOSECTOR: u32 = 0x0000_0008;
/// `MF_NOBLOCKMAP` - don't use the blockmap links (inert but displayable).
pub const MF_NOBLOCKMAP: u32 = 0x0000_0010;
/// `MF_AMBUSH` - not to be activated by sound; deaf monster.
pub const MF_AMBUSH: u32 = 0x0000_0020;
/// `MF_JUSTHIT` - will try to attack right back.
pub const MF_JUSTHIT: u32 = 0x0000_0040;
/// `MF_JUSTATTACKED` - will take at least one step before attacking.
pub const MF_JUSTATTACKED: u32 = 0x0000_0080;
/// `MF_SPAWNCEILING` - spawn hanging from the ceiling (initial position).
pub const MF_SPAWNCEILING: u32 = 0x0000_0100;
/// `MF_NOGRAVITY` - don't apply gravity every tic; float instead.
pub const MF_NOGRAVITY: u32 = 0x0000_0200;
/// `MF_DROPOFF` - allow moves from high places off a step.
pub const MF_DROPOFF: u32 = 0x0000_0400;
/// `MF_PICKUP` - for players, will pick up items.
pub const MF_PICKUP: u32 = 0x0000_0800;
/// `MF_NOCLIP` - player cheat; no collision.
pub const MF_NOCLIP: u32 = 0x0000_1000;
/// `MF_SLIDE` - keep info about sliding along walls.
pub const MF_SLIDE: u32 = 0x0000_2000;
/// `MF_FLOAT` - allow moves to any height, no gravity (e.g. cacodemons).
pub const MF_FLOAT: u32 = 0x0000_4000;
/// `MF_TELEPORT` - don't cross lines (or look at heights on teleport).
pub const MF_TELEPORT: u32 = 0x0000_8000;
/// `MF_MISSILE` - don't hit same species, explode on block (monster fireballs, player missiles).
pub const MF_MISSILE: u32 = 0x0001_0000;
/// `MF_DROPPED` - dropped by a demon, not level spawned (e.g. clips dropped by dying former humans).
pub const MF_DROPPED: u32 = 0x0002_0000;
/// `MF_SHADOW` - use fuzzy draw (spectres, invisibility powerup).
pub const MF_SHADOW: u32 = 0x0004_0000;
/// `MF_NOBLOOD` - don't bleed when shot; barrels and furniture shall not bleed.
pub const MF_NOBLOOD: u32 = 0x0008_0000;
/// `MF_CORPSE` - don't stop moving halfway off a step; slide down all the way.
pub const MF_CORPSE: u32 = 0x0010_0000;
/// `MF_INFLOAT` - floating to a height for a move; don't auto-float to target's height.
pub const MF_INFLOAT: u32 = 0x0020_0000;
/// `MF_COUNTKILL` - count towards intermission kill total.
pub const MF_COUNTKILL: u32 = 0x0040_0000;
/// `MF_COUNTITEM` - count towards intermission item total.
pub const MF_COUNTITEM: u32 = 0x0080_0000;
/// `MF_SKULLFLY` - special handling: skull in flight (neither cacodemon nor missile).
pub const MF_SKULLFLY: u32 = 0x0100_0000;
/// `MF_NOTDMATCH` - don't spawn this object in deathmatch mode (e.g. key cards).
pub const MF_NOTDMATCH: u32 = 0x0200_0000;
/// `MF_TRANSLATION` - mask for the player translation range (vanilla `0xc000000`).
pub const MF_TRANSLATION: u32 = 0x0c00_0000;
/// `MF_TRANSSHIFT` - shift to extract the player translation (vanilla `26`).
pub const MF_TRANSSHIFT: u32 = 26;

