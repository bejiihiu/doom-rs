/// The gamma table for a level.
///
/// The original indexes the table with an unchecked `usegamma` from the
/// config; values outside 0..=4 would read out of bounds there. We clamp
/// instead — config values are validated at load time, but a clamp keeps
/// this function total.
pub const fn level_table(level: usize) -> &'static [u8; 256] {
    if level >= GAMMA_LEVELS {
        &GAMMA_TABLE[GAMMA_LEVELS - 1]
    } else {
        &GAMMA_TABLE[level]
    }
}

/// Remaps palette index `value` through the gamma table for `level`.
pub fn gamma_remap(level: usize, value: u8) -> u8 {
    level_table(level)[value as usize]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn row_zero_spot_values() {
        // known values from the original table: 1,2,...,127,128,128,129,...
        let row = &GAMMA_TABLE[0];
        assert_eq!(row[0], 1);
        assert_eq!(row[126], 127);
        assert_eq!(row[127], 128);
        assert_eq!(row[128], 128);
        assert_eq!(row[129], 129);
        assert_eq!(row[255], 255);
    }

    #[test]
    fn row_heads_double_each_level() {
        // the first entry of each level is 1, 2, 4, 8, 16
        let heads = [
            GAMMA_TABLE[0][0],
            GAMMA_TABLE[1][0],
            GAMMA_TABLE[2][0],
            GAMMA_TABLE[3][0],
            GAMMA_TABLE[4][0],
        ];
        assert_eq!(heads, [1, 2, 4, 8, 16]);
    }

    #[test]
    fn every_row_ends_at_255() {
        for row in &GAMMA_TABLE {
            assert_eq!(row[255], 255);
        }
    }

    #[test]
    fn every_row_is_non_decreasing() {
        for (level, row) in GAMMA_TABLE.iter().enumerate() {
            for pair in row.windows(2) {
                assert!(pair[0] <= pair[1], "gamma level {level} dips");
            }
        }
    }

    #[test]
    fn higher_levels_are_at_least_as_bright_at_zero() {
        // each level lifts the darkest colors more than the previous one
        assert!(GAMMA_TABLE[0][0] < GAMMA_TABLE[1][0]);
        assert!(GAMMA_TABLE[1][0] < GAMMA_TABLE[2][0]);
        assert!(GAMMA_TABLE[2][0] < GAMMA_TABLE[3][0]);
        assert!(GAMMA_TABLE[3][0] < GAMMA_TABLE[4][0]);
    }

    #[test]
    fn gamma_remap_matches_table() {
        for (level, table) in GAMMA_TABLE.iter().enumerate() {
            for value in [0u8, 1, 100, 200, 255] {
                assert_eq!(gamma_remap(level, value), table[value as usize]);
            }
        }
    }

    #[test]
    fn out_of_range_levels_clamp() {
        assert_eq!(
            gamma_remap(GAMMA_LEVELS, 0),
            GAMMA_TABLE[GAMMA_LEVELS - 1][0]
        );
        assert_eq!(
            gamma_remap(usize::MAX, 42),
            GAMMA_TABLE[GAMMA_LEVELS - 1][42]
        );
    }
}
